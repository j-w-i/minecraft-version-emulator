package net.historicalexperience.version;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.EnumSet;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

/**
 * Level: unit. Generates {@code docs/VERSION_MATRIX.md} from the live registry and fails if the committed copy is stale.
 *
 * <p>The question this answers is the one the whole refactor is for: <em>what defines this version's behaviour?</em>
 * For any version, the matrix lists where it is declared, its position on the timeline, and exactly which features are
 * active in it - so a developer can see the answer without searching the repository, and cannot get an answer that has
 * drifted from the code, because the document is produced by this test.
 *
 * <p>Run with {@code HEX_DOCS_UPDATE=1} to rewrite it. That is deliberately opt-in: a test that silently rewrites the
 * file would also silently accept a wrong window.
 *
 * <p>The heading says "matches the implementation", not "historically verified". Those are different claims, and this
 * project keeps them apart: a feature's evidence string states how well it is known, and a version whose rules are
 * inferred says so in its own evidence.
 */
class VersionMatrixTest {
    private static final Path DOC = Path.of("docs/VERSION_MATRIX.md");

    @Test
    @DisplayName("the version matrix documents every version and every feature, and matches the code")
    void matrixIsCurrent() throws IOException {
        String generated = generate();
        if ("1".equals(System.getenv("HEX_DOCS_UPDATE"))) {
            Files.createDirectories(DOC.getParent());
            Files.writeString(DOC, generated, StandardCharsets.UTF_8);
            return;
        }
        assertTrue(Files.isRegularFile(DOC),
            "docs/VERSION_MATRIX.md is missing; run the tests with HEX_DOCS_UPDATE=1 to generate it");
        String committed = Files.readString(DOC, StandardCharsets.UTF_8).replace("\r\n", "\n");
        assertEquals(generated, committed,
            "docs/VERSION_MATRIX.md is stale: re-run with HEX_DOCS_UPDATE=1 and commit it. The matrix is generated so "
                + "that it cannot describe a window the code does not have.");
    }

    /** The document, as text. Deterministic: versions by chronology, features by declaration order. */
    static String generate() {
        List<HistoricalVersion> versions = HistoricalVersions.chronological();
        StringBuilder out = new StringBuilder();
        out.append("# Version matrix\n\n")
            .append("<!-- GENERATED by VersionMatrixTest. Do not edit by hand: run the test suite with\n")
            .append("     HEX_DOCS_UPDATE=1 to rewrite it. The heading claim is deliberate: this file matches the\n")
            .append("     IMPLEMENTATION, which is not the same claim as 'historically verified'. Each feature's\n")
            .append("     evidence string, in section 3, is where that second claim is made. -->\n\n")
            .append("## 1. The declared versions\n\n")
            .append("Oldest first. *Rules* are the version's own data (hunger, sprinting, experience, structures, ")
            .append("drop and food tables); *features* are the historical differences the code applies to it. A ")
            .append("version's behaviour is exactly these two things plus the mechanics that read them.\n\n")
            .append("| Version | Family | Key | Recipe revisions | Rules (from its own evidence) | Features | Spawns |\n")
            .append("|---|---|---|---|---|---|---|\n");

        for (HistoricalVersion version : versions) {
            List<Feature> active = activeFeatures(version);
            out.append("| `").append(version.id()).append("` | ").append(version.family()).append(" | ")
                .append(version.chronology()).append(" | ")
                .append(version.revisions().size()).append(" | ")
                .append(summary(version)).append(" | ")
                .append(active.size()).append(" of ").append(Feature.values().length)
                .append(" | ")
                .append(version.rules().restrictsSpawns()
                    ? version.rules().allowedNaturalSpawns().size() + " allowed" : "unrestricted")
                .append(" |\n");
        }

        out.append("\n## 2. Which features apply where\n\n")
            .append("`#` = active in that version. Columns are the versions above, in the same order, abbreviated to ")
            .append("the part of the id after `historical_experience:`.\n\n");
        out.append("| Feature |");
        for (HistoricalVersion version : versions) {
            out.append(" ").append(shortName(version.id())).append(" |");
        }
        out.append("\n|---|");
        for (int i = 0; i < versions.size(); i++) {
            out.append("---|");
        }
        out.append("\n");
        for (Feature feature : Feature.values()) {
            out.append("| `").append(feature.name()).append("` |");
            for (HistoricalVersion version : versions) {
                out.append(Features.active(feature, version) ? " # |" : " |");
            }
            out.append("\n");
        }

        out.append("\n## 3. Every feature: window, evidence\n\n")
            .append("Active when any window contains the version. `[from, until)` is half-open; `exact` matches one ")
            .append("declared build by id; `all declared` means the true boundary lies beyond the newest declared ")
            .append("build. The evidence column is where the research stops and the inference starts.\n\n")
            .append("| Feature | Domain | Window | Evidence |\n|---|---|---|---|\n");
        for (Feature feature : Feature.values()) {
            out.append("| `").append(feature.name()).append("` | ").append(feature.domain()).append(" | ")
                .append(windows(feature)).append(" | ")
                .append(escape(feature.evidence())).append(" |\n");
        }

        out.append("\n## 4. How to read a row\n\n")
            .append("To change what a version does, change the **feature window** (one line in `Feature`), the ")
            .append("**version's own data** (`legacy/LegacyCatalog`: spawn set, drops, food heals, generation ")
            .append("revisions), or the **implementation** of the mechanic. Do not add a version check anywhere else: ")
            .append("`ArchitectureLintTest` fails on one. Adding a version is described in ")
            .append("[ADDING_VERSIONS.md](ADDING_VERSIONS.md); adding a behaviour is in ")
            .append("[ADDING_FEATURES.md](ADDING_FEATURES.md).\n");
        return out.toString();
    }

    /** The id without the namespace, which is what a reader recognises. */
    private static String shortName(String id) {
        int colon = id.indexOf(':');
        return colon < 0 ? id : id.substring(colon + 1);
    }

    private static List<Feature> activeFeatures(HistoricalVersion version) {
        List<Feature> active = new ArrayList<>();
        for (Feature feature : Feature.values()) {
            if (Features.active(feature, version)) {
                active.add(feature);
            }
        }
        return active;
    }

    private static String names(List<Feature> features) {
        List<String> names = new ArrayList<>();
        features.forEach(feature -> names.add("`" + feature.name() + "`"));
        return String.join(", ", names);
    }

    private static String summary(HistoricalVersion version) {
        var rules = version.rules();
        List<String> facts = new ArrayList<>();
        facts.add(rules.hasHunger() ? "hunger" : "no hunger");
        facts.add(rules.allowsSprinting() ? "sprinting" : "no sprinting");
        facts.add(rules.awardsExperience() ? "experience" : "no experience");
        facts.add(rules.hasStructures() ? "structures" : "no structures");
        if (rules.replacesLoot()) {
            facts.add(rules.mobDrops().size() + " drop rules");
        }
        if (!rules.foodHealPoints().isEmpty()) {
            facts.add(rules.foodHealPoints().size() + " food heals");
        }
        return String.join(", ", facts);
    }

    private static String windows(Feature feature) {
        List<String> described = new ArrayList<>();
        for (FeatureWindow window : feature.windows()) {
            if (window instanceof FeatureWindow.Range range) {
                String from = range.from() == null ? "-inf" : range.from().label();
                String until = range.until() == null ? "+inf" : range.until().label();
                described.add("[" + from + ", " + until + ")");
            } else if (window instanceof FeatureWindow.Exact exact) {
                described.add("exact `" + exact.id() + "`");
            } else {
                described.add("all declared");
            }
        }
        return String.join(" or ", described);
    }

    private static String escape(String text) {
        return text.replace("|", "\\|").replace("\n", " ").replaceAll("\\s+", " ").trim();
    }

    /** Guards the shape of the document, so a broken generator cannot pass by producing something empty. */
    @Test
    @DisplayName("the matrix covers every version and every feature")
    void matrixIsComplete() {
        String text = generate();
        for (HistoricalVersion version : HistoricalVersions.all()) {
            assertTrue(text.contains("`" + version.id() + "`"), "missing version " + version.id());
        }
        for (Feature feature : EnumSet.allOf(Feature.class)) {
            assertTrue(text.contains("`" + feature.name() + "`"), "missing feature " + feature.name());
        }
        Map<String, Integer> domains = new TreeMap<>();
        for (Feature feature : Feature.values()) {
            domains.merge(feature.domain().name(), 1, Integer::sum);
        }
        assertTrue(domains.size() >= 5, "the matrix should span the domains, got " + domains);
    }
}
