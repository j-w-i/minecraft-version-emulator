/**
 * Level: unit. Writes {@code research/version-facts.md}: one section per declared version, listing what the code actually
 * does for it - its rules, its active features, its spawn set, drops, food, enchantments, what it refuses, its
 * structures, its visual profile and its generation recipes.
 *
 * <p>This is the "actual" column of a fidelity audit. It exists because an audit that works from memory or from the
 * prose in the docs is how a wrong claim survives: every line here is read back from the same APIs the game calls, so
 * comparing it with history is a comparison of fact against evidence rather than of document against document.
 *
 * <p>Run with {@code HEX_DOCS_UPDATE=1} to rewrite the file; it is a research artefact, not a golden master, so no test
 * asserts its contents (a stale copy is corrected by re-running, not by failing the build).
 */
class VersionFactsTest {
    private static final Path FACTS = Path.of("research/version-facts.md");

    /** The mobs the drop tables talk about, so a reader sees the whole substitution set. */
    private static final List<String> DROP_ENTITIES = List.of(
        "minecraft:zombie", "minecraft:chicken", "minecraft:spider", "minecraft:cow", "minecraft:creeper",
        "minecraft:skeleton", "minecraft:pig", "minecraft:sheep");

    @Test
    @DisplayName("the facts file is generated from the live APIs")
    void factsAreCurrent() throws IOException {
        String generated = generate();
        if ("1".equals(System.getenv("HEX_DOCS_UPDATE"))) {
            Files.createDirectories(FACTS.getParent());
            Files.writeString(FACTS, generated, StandardCharsets.UTF_8);
            return;
        }
        assertFalse(generated.isBlank(), "the facts generator produced nothing");
        assertTrue(generated.contains("## "), "the facts generator produced no version sections");
    }

    static String generate() {
        StringBuilder out = new StringBuilder();
        out.append("# Version facts - what the code does, per declared version\n\n")
            .append("<!-- GENERATED by VersionFactsTest (HEX_DOCS_UPDATE=1). Every line is read back from the same\n")
            .append("     APIs the game calls, so this is the ACTUAL side of a fidelity audit. It makes no claim about\n")
            .append("     whether the behaviour is historically right: compare it with research/feature-timeline.json,\n")
            .append("     research/version-boundaries.json and the wiki history pages. See docs/VERSION_GAPS.md. -->\n\n");

        for (HistoricalVersion version : HistoricalVersions.chronological()) {
            out.append("## ").append(version.displayName()).append(" (`").append(version.id()).append("`)\n\n");
            out.append("- family ").append(version.family()).append(", key ").append(version.chronology())
                .append(", revisions ").append(version.revisions().size()).append("\n");
            out.append("- rules: ").append(rules(version)).append("\n");
            out.append("- evidence: ").append(escape(version.rules().evidence())).append("\n\n");

            out.append("**Features active (").append(activeFeatures(version).size()).append("):** ")
                .append(joinOrDash(activeFeatures(version))).append("\n\n");

            out.append("**Generation recipes:** ");
            List<String> revisions = new ArrayList<>();
            for (HistoricalVersion.GenerationRevision revision : version.revisions()) {
                revisions.add("`" + revision.alias() + "` (rev " + revision.revision() + ", from "
                    + revision.foundation() + ", " + revision.excludedPlacedFeatures().size() + " exclusions, "
                    + revision.orePopulation().size() + " ore rules"
                    + (revision.experimental() ? ", experimental" : "") + ")");
            }
            out.append(String.join("; ", revisions)).append("\n\n");

            out.append("**Spawns:** ").append(spawns(version)).append("\n\n");
            out.append("**Drops:** ").append(drops(version)).append("\n\n");
            out.append("**Food:** ").append(food(version)).append("\n\n");
            out.append("**Enchantments:** ").append(enchantments(version)).append("\n\n");
            out.append("**Crafting:** ").append(crafting(version)).append("\n\n");
            out.append("**Structures:** ").append(structures(version)).append("\n\n");
            out.append("**Blocks judged anachronistic:** ").append(blockVerdicts(version)).append("\n\n");
            out.append("**Visual profile:** ").append(visuals(version)).append("\n\n");
            out.append("**World rules:** ").append(world(version)).append("\n\n");
        }
        return out.toString();
    }

    private static String rules(HistoricalVersion version) {
        HistoricalVersion.VersionRules rules = version.rules();
        List<String> facts = new ArrayList<>();
        facts.add(rules.hasHunger() ? "hunger" : "no hunger");
        facts.add(rules.allowsSprinting() ? "sprinting" : "no sprinting");
        facts.add(rules.awardsExperience() ? "experience" : "no experience");
        facts.add(rules.hasStructures() ? "structures" : "no structures");
        facts.add(rules.restrictsSpawns()
            ? rules.allowedNaturalSpawns().size() + " spawns allowed" : "spawning unrestricted");
        facts.add(rules.replacesLoot() ? rules.mobDrops().size() + " drop rules" : "drops modern");
        facts.add(rules.foodHealPoints().isEmpty()
            ? "no direct food healing" : rules.foodHealPoints().size() + " direct food heals");
        return String.join(", ", facts);
    }

    private static List<String> activeFeatures(HistoricalVersion version) {
        List<String> active = new ArrayList<>();
        for (Feature feature : Feature.values()) {
            if (Features.active(feature, version)) {
                active.add("`" + feature.name() + "`");
            }
        }
        return active;
    }

    private static String spawns(HistoricalVersion version) {
        var rule = HistoricalSpawnRules.forProfile(version.id());
        if (rule.isEmpty()) {
            return "unrestricted (modern spawn set applies)";
        }
        return rule.get().allowedEntityTypes().size() + " allowed: " + new TreeSet<>(rule.get().allowedEntityTypes());
    }

    private static String drops(HistoricalVersion version) {
        List<String> facts = new ArrayList<>();
        for (String entity : DROP_ENTITIES) {
            var rule = HistoricalLootRules.forEntity(version.id(), entity);
            if (rule.isPresent()) {
                facts.add(entity.substring("minecraft:".length()) + " -> "
                    + rule.get().itemId().substring("minecraft:".length()) + " (0.." + (rule.get().maxExclusiveCount() - 1)
                    + ")");
            }
        }
        return facts.isEmpty() ? "modern drop tables" : String.join("; ", facts);
    }

    private static String food(HistoricalVersion version) {
        // Two different questions, and conflating them once produced a wrong audit finding: the DECLARED table is what
        // the version's rules record, while the EFFECTIVE healing is what the food hook applies. A no-hunger version
        // with an empty declared table still heals, because researchedHeal falls back to the pre-1.8 table on purpose.
        if (HistoricalFoodRules.healsFoodDirectly(version.id())) {
            return HistoricalFoodRules.healPoints(version.id()).size() + " declared direct heals: "
                + HistoricalFoodRules.healPoints(version.id());
        }
        if (!HistoricalFoodRules.hasHunger(version.id())) {
            return "no declared heal table; EFFECTIVE healing falls back to the pre-1.8 table ("
                + HistoricalFoodRules.BETA_1_7_3_HEAL_POINTS.size() + " items, see researchedHeal) - eating heals";
        }
        return "hunger values only (see BETA_FOOD_HUNGER_VALUES); eating does not heal directly";
    }

    private static String enchantments(HistoricalVersion version) {
        List<String> available = new ArrayList<>();
        for (var key : HistoricalEnchanting.all().keySet()) {
            if (HistoricalEnchanting.available(version.id(), key)) {
                available.add(key.location().getPath());
            }
        }
        return available.isEmpty() ? "none" : available.size() + ": " + new TreeSet<>(available);
    }

    private static String crafting(HistoricalVersion version) {
        // TWO different gates, and probing only the first once produced a wrong audit finding: isRefused(.., blockId)
        // also asks the block-availability table whether the RESULT BLOCK is anachronistic, and the in-game call site
        // always passes a block id for a block item. Passing null measured only the item allow-list, so a Release 1.3
        // world looked as if it could craft hoppers when the block gate refuses them. Probe both and report both.
        List<String> refused = new ArrayList<>();
        List<String> refusedAsBlock = new ArrayList<>();
        for (String id : new TreeSet<>(HistoricalCraftingEra.allowListed())) {
            if (HistoricalCraftingEra.isRefused(version.id(), id, null)
                    && !RemovedRecipes.replacesModernRecipe(version.id(), id)) {
                refused.add(id.substring("minecraft:".length()));
            } else if (HistoricalCraftingEra.isRefused(version.id(), id, id)) {
                refusedAsBlock.add(id.substring("minecraft:".length()));
            }
        }
        int allowListed = HistoricalCraftingEra.allowListed().size();
        String removed = RemovedRecipes.appliesTo(version.id())
            ? "; REMOVED-RECIPE recipes supplied: " + RemovedRecipes.all().stream()
                .map(RemovedRecipes.Removed::result).toList()
            : "";
        return allowListed + " allow-listed ids, " + refused.size() + " refused by the item gate"
            + (refused.isEmpty() ? "" : ": " + refused)
            + ", " + refusedAsBlock.size() + " refused by the BLOCK-DATE gate"
            + (refusedAsBlock.isEmpty() ? "" : ": " + refusedAsBlock) + removed;
    }

    private static String structures(HistoricalVersion version) {
        var rule = HistoricalStructureRules.ruleForVersion(version.id());
        return rule.isEmpty() ? "no rule (modern structure placement applies)"
            : (rule.get().restricts() ? "restricted to " + new TreeSet<>(rule.get().allowedStructureIds())
                : "unrestricted");
    }

    private static String blockVerdicts(HistoricalVersion version) {
        int anachronistic = 0;
        int unknown = 0;
        List<String> names = new ArrayList<>();
        for (String block : new TreeSet<>(HistoricalBlockAvailability.all().keySet())) {
            var verdict = HistoricalBlockAvailability.judge(version.id(), block);
            if (verdict == HistoricalBlockAvailability.Verdict.ANACHRONISTIC) {
                anachronistic++;
                names.add(block.substring("minecraft:".length()));
            } else if (verdict == HistoricalBlockAvailability.Verdict.UNKNOWN) {
                unknown++;
            }
        }
        return anachronistic + " recorded anachronistic, " + unknown + " unknown of "
            + HistoricalBlockAvailability.all().size() + (names.isEmpty() ? "" : ": " + names);
    }

    private static String visuals(HistoricalVersion version) {
        List<String> facts = new ArrayList<>();
        facts.add("textures " + HistoricalTextureRules.planFor(version).signature());
        facts.add("stars " + HistoricalStars.styleFor(version));
        facts.add("tooltips " + HistoricalTooltips.eraFor(version.chronology()));
        facts.add("label " + (HistoricalVersionLabel.shownIn(version) ? "shown" : "hidden"));
        facts.add("old lighting " + HistoricalOldLighting.availableFor(version));
        facts.add("smooth lighting " + HistoricalSmoothLighting.availableFor(version));
        facts.add("lighting tweaks " + HistoricalLightingTweaks.availableFor(version));
        facts.add("fog " + HistoricalFogTweaks.beforeBeta18(version));
        facts.add("chest " + HistoricalChestTweaks.availableForChest(version)
            + ", ender chest " + HistoricalChestTweaks.availableForEnderChest(version));
        facts.add("sky " + HistoricalWorldTweaks.skyEra(version) + " " + HistoricalWorldTweaks.eraSkyColour(version));
        facts.add("colormaps " + HistoricalColormaps.eraSignatureFor(version.chronology()));
        facts.add("cloud height " + HistoricalWorldTweaks.cloudHeightForVersion(128f, version));
        return String.join("; ", facts);
    }

    private static String world(HistoricalVersion version) {
        List<String> facts = new ArrayList<>();
        facts.add("weather " + HistoricalWeather.existsIn(version));
        facts.add("villages " + HistoricalVillageRules.generationEnabledForVersion(version.id()));
        facts.add("left-click use " + HistoricalLeftClickEvents.availableFor(version));
        facts.add("sprinting " + HistoricalPlayerRules.allowsSprinting(version.id()));
        facts.add("finite world " + HistoricalVersions.isFiniteWorld(version.id()));
        return String.join("; ", facts);
    }

    private static String joinOrDash(List<String> values) {
        return values.isEmpty() ? "-" : String.join(", ", values);
    }

    private static String escape(String text) {
        return text.replace("\n", " ").replaceAll("\\s+", " ").trim();
    }
}
