package net.historicalexperience.worldgen;

import net.historicalexperience.HistoricalExperience;
import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.world.level.levelgen.structure.StructureType;
import net.minecraft.world.level.levelgen.structure.pieces.StructurePieceType;

/**
 * The two registry entries this structure needs, registered through plain Fabric/vanilla registries.
 *
 * <h2>Why not a mixin, and why not a DeferredRegister</h2>
 *
 * <p>Upstream registers both through NeoForge's {@code DeferredRegister}, which is loader glue: it exists
 * to time registration against a mod event bus. On 1.21.1/Fabric both registries are ordinary frozen
 * registries that are still open during a mod initialiser, so {@link Registry#register} is the whole
 * mechanism and no mixin is needed. That also means this class can be called from
 * {@link net.historicalexperience.HistoricalExperienceMod#onInitialize()} with no event plumbing.
 *
 * <p>The piece type matters more than it looks: it is the {@code id} written into every saved chunk's
 * structure data, so a chunk generated by this structure and reloaded resolves its pieces through the
 * factory registered here. An unregistered piece type would not fail at generation time - it would fail
 * the first time a world with a village was loaded, which is the worst place to find out.
 */
public final class HistoricalVillageTypes {
    /** The structure type id: {@code historical_experience:historical_village}. */
    public static final StructureType<HistoricalVillageStructure> HISTORICAL_VILLAGE =
        () -> HistoricalVillageStructure.CODEC;

    /** The piece type id: {@code historical_experience:historical_village_piece}. */
    public static final StructurePieceType HISTORICAL_VILLAGE_PIECE =
        (context, tag) -> new HistoricalVillagePieces.VillagePiece(
            HistoricalVillageTypes.HISTORICAL_VILLAGE_PIECE, tag);

    private static boolean registered;

    private HistoricalVillageTypes() {
    }

    /** Registers both types. Idempotent, so a test or a second initialiser cannot double-register. */
    public static synchronized void register() {
        if (registered) {
            return;
        }
        Registry.register(BuiltInRegistries.STRUCTURE_TYPE,
            HistoricalExperience.id("historical_village"), HISTORICAL_VILLAGE);
        Registry.register(BuiltInRegistries.STRUCTURE_PIECE,
            HistoricalExperience.id("historical_village_piece"), HISTORICAL_VILLAGE_PIECE);
        registered = true;
    }

    /** Whether {@link #register()} has run, for the diagnostics report. */
    public static boolean isRegistered() {
        return registered
            && BuiltInRegistries.STRUCTURE_TYPE.containsKey(
                HistoricalExperience.id("historical_village"))
            && BuiltInRegistries.STRUCTURE_PIECE.containsKey(
                HistoricalExperience.id("historical_village_piece"));
    }

    /** The registry ids, so a report or a test can name what it checked. */
    public static net.minecraft.resources.ResourceLocation structureTypeId() {
        return HistoricalExperience.id("historical_village");
    }

    /** The piece type id. */
    public static net.minecraft.resources.ResourceLocation pieceTypeId() {
        return HistoricalExperience.id("historical_village_piece");
    }

    /** The structure id the data file must declare. */
    public static net.minecraft.resources.ResourceLocation structureId() {
        return HistoricalExperience.id("historical_village");
    }

    /** The structure-set id the data file must declare. */
    public static net.minecraft.resources.ResourceLocation structureSetId() {
        return HistoricalExperience.id("historical_villages");
    }

    /** The biome tag a structure references, in the {@code #namespace:path} form the JSON needs. */
    public static String biomeTagReference() {
        return "#" + HistoricalExperience.MOD_ID + ":has_structure/historical_village";
    }

    /** The registry id of that biome tag. */
    public static net.minecraft.resources.ResourceLocation biomeTagId() {
        return HistoricalExperience.id("has_structure/historical_village");
    }
}
