import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * What each historical version added, changed and removed, for the version selector's overview panel.
 *
 * <p>The data is {@code version_overview.json}, generated by {@code scripts/generate-version-overview.ps1} from
 * {@code research/version-transitions.json}. It is read once and cached. A missing or unreadable file is not an error
 * the player should meet: the selector simply has no overview to show, which is the honest answer, rather than a
 * crash on a screen whose job is to choose a version.
 *
 * <p>The research behind it says it is "in progress; not yet exhaustive", so an item missing from a list is never
 * evidence that the feature was absent in that build. The selector says so under the panel.
 */
public final class VersionOverview {
    private static final Logger LOGGER = LoggerFactory.getLogger("historical_experience/version-overview");
    private static final String RESOURCE = "assets/historical_experience/version_overview.json";

    private static final Map<String, Overview> CACHE = new ConcurrentHashMap<>();
    private static volatile boolean loaded;

    private VersionOverview() {
    }

    /** One version's four lists. Each is immutable and never null. */
    public record Overview(List<String> introduced, List<String> changed, List<String> removed,
            List<String> worldgen) {
        public Overview {
            introduced = List.copyOf(introduced);
            changed = List.copyOf(changed);
            removed = List.copyOf(removed);
            worldgen = List.copyOf(worldgen);
        }

        /** Whether there is anything at all to show. */
        public boolean isEmpty() {
            return this.introduced.isEmpty() && this.changed.isEmpty() && this.removed.isEmpty()
                && this.worldgen.isEmpty();
        }
    }

    /** The overview for a profile id such as {@code historical_experience:beta_1_8_1}, when one is recorded. */
    public static Optional<Overview> forVersion(String versionKey) {
        ensureLoaded();
        return Optional.ofNullable(CACHE.get(versionKey)).filter(overview -> !overview.isEmpty());
    }

    private static void ensureLoaded() {
        if (loaded) {
            return;
        }
        synchronized (VersionOverview.class) {
            if (loaded) {
                return;
            }
            try (InputStream stream = VersionOverview.class.getClassLoader().getResourceAsStream(RESOURCE)) {
                if (stream == null) {
                    LOGGER.warn("{} is not in the jar; the version selector will show no overview", RESOURCE);
                } else {
                    parse(new InputStreamReader(stream, StandardCharsets.UTF_8));
                }
            } catch (IOException | RuntimeException failure) {
                // A corrupt file must not break the version screen; it just has nothing to show.
                LOGGER.error("Could not read {}; the version selector will show no overview", RESOURCE, failure);
                CACHE.clear();
            }
            loaded = true;
        }
    }

    /** Parses the document into the cache. Package-visible so a test can feed it text instead of a jar. */
    static void parse(java.io.Reader reader) {
        JsonObject root = JsonParser.parseReader(reader).getAsJsonObject();
        JsonObject versions = root.getAsJsonObject("versions");
        if (versions == null) {
            return;
        }
        for (Map.Entry<String, JsonElement> entry : versions.entrySet()) {
            JsonObject version = entry.getValue().getAsJsonObject();
            CACHE.put(entry.getKey(), new Overview(strings(version, "introduced"), strings(version, "changed"),
                strings(version, "removed"), strings(version, "worldgen")));
        }
    }

    private static List<String> strings(JsonObject object, String name) {
        List<String> out = new ArrayList<>();
        JsonArray array = object.getAsJsonArray(name);
        if (array != null) {
            for (JsonElement element : array) {
                if (element.isJsonPrimitive() && !element.getAsString().isBlank()) {
                    out.add(element.getAsString().strip());
                }
            }
        }
        return out;
    }
}